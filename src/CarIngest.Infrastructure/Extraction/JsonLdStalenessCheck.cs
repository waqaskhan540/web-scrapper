using System.Globalization;
using AngleSharp.Dom;

namespace CarIngest.Infrastructure.Extraction;

/// <summary>Result of cross-validating a JSON-LD value against the rendered page.</summary>
public sealed record StalenessFinding(bool Mismatch, decimal? StructuredPrice, decimal? VisiblePrice)
{
    public static StalenessFinding NotChecked => new(Mismatch: false, null, null);
}

/// <summary>
/// Cross-validates the JSON-LD price against a visible DOM anchor.
/// </summary>
/// <remarks>
/// <para>
/// JSON-LD is drift-resistant against layout changes, but it is not guaranteed to agree with
/// what the page shows: the two are often generated by different code paths, and a cached or
/// stale structured-data block can advertise last week's price while the visible page shows
/// today's (research D9, failure mode 2).
/// </para>
/// <para>
/// A mismatch is <b>flagged, not resolved</b>. Picking a winner would mean guessing which code
/// path is authoritative, and guessing wrong silently stores a wrong price. Flagging lets an
/// operator decide per host.
/// </para>
/// </remarks>
internal static class JsonLdStalenessCheck
{
    /// <summary>Selectors in decreasing order of how explicitly they mark a price.</summary>
    private static readonly string[] PriceAnchors =
    [
        "[itemprop='price']",
        "[data-price]",
        ".price",
        "#price",
    ];

    internal static StalenessFinding Check(IDocument document, decimal? structuredPrice)
    {
        ArgumentNullException.ThrowIfNull(document);

        if (structuredPrice is null)
        {
            return StalenessFinding.NotChecked;
        }

        var visible = ReadVisiblePrice(document);
        if (visible is null)
        {
            // No anchor to compare against is not a mismatch — most pages have no machine
            // readable price outside the JSON-LD, and treating that as a fault would reject
            // almost everything.
            return StalenessFinding.NotChecked;
        }

        // A penny of rounding is not drift; a different price is.
        var mismatch = Math.Abs(visible.Value - structuredPrice.Value) > 0.01m;
        return new StalenessFinding(mismatch, structuredPrice, visible);
    }

    private static decimal? ReadVisiblePrice(IDocument document)
    {
        foreach (var selector in PriceAnchors)
        {
            foreach (var element in document.QuerySelectorAll(selector))
            {
                var candidate = element.GetAttribute("data-price")
                    ?? element.GetAttribute("content")
                    ?? element.TextContent;

                if (TryParsePrice(candidate, out var price))
                {
                    return price;
                }
            }
        }

        return null;
    }

    private static bool TryParsePrice(string? text, out decimal price)
    {
        price = 0m;

        if (string.IsNullOrWhiteSpace(text))
        {
            return false;
        }

        // Strip currency symbols, thousands separators, and surrounding words so "£12,000"
        // and "12000.00" compare equal.
        var cleaned = new string([.. text.Where(c => char.IsDigit(c) || c == '.')]);

        return cleaned.Length > 0
            && decimal.TryParse(cleaned, NumberStyles.Number, CultureInfo.InvariantCulture, out price);
    }
}
